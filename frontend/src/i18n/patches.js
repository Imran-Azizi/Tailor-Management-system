const mergeLocalePatch = (target, patch) => {
  for (const [key, value] of Object.entries(patch)) {
    if (
      value &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      target[key] &&
      typeof target[key] === "object" &&
      !Array.isArray(target[key])
    ) {
      mergeLocalePatch(target[key], value);
    } else {
      target[key] = value;
    }
  }
  return target;
};

