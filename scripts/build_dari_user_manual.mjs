function esc(value = "") {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function writeFile(rel, content) {
  const target = path.join(tmpDir, rel);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content, "utf8");
}

function rPr({ bold = false, color = "111827", size = 22 } = {}) {
  return [
    "<w:rPr>",
    '<w:rFonts w:ascii="Arial" w:hAnsi="Arial" w:cs="Arial"/>',
    bold ? "<w:b/><w:bCs/>" : "",
    `<w:color w:val="${color}"/>`,
    `<w:sz w:val="${size}"/><w:szCs w:val="${size}"/>`,
    "<w:rtl/>",
    "</w:rPr>",
  ].join("");
}

function run(text, opts = {}) {
  const lines = String(text ?? "").split("\n");
  return `<w:r>${rPr(opts)}${lines
    .map((line, index) =>
      `${index ? "<w:br/>" : ""}<w:t xml:space="preserve">${esc(line)}</w:t>`,
    )
    .join("")}</w:r>`;
}

function para(text, opts = {}) {
  const {
    style = "Normal",
    align = "right",
    before = 0,
    after = 120,
    line = 300,
    bold = false,
    color,
    size,
    numId = null,
    ilvl = 0,
    pageBreakBefore = false,
    keepNext = false,
    indent = null,
  } = opts;
  return [
    "<w:p>",
    "<w:pPr>",
    `<w:pStyle w:val="${style}"/>`,
    "<w:bidi/>",
    `<w:jc w:val="${align}"/>`,
    `<w:spacing w:before="${before}" w:after="${after}" w:line="${line}" w:lineRule="auto"/>`,
    keepNext ? "<w:keepNext/>" : "",
    pageBreakBefore ? "<w:pageBreakBefore/>" : "",
    indent ? `<w:ind w:right="${indent}" w:left="0"/>` : "",
    numId
      ? `<w:numPr><w:ilvl w:val="${ilvl}"/><w:numId w:val="${numId}"/></w:numPr>`
      : "",
    "</w:pPr>",
    run(text, { bold, color, size }),
    "</w:p>",
  ].join("");
}

function heading(text, level = 1, pageBreakBefore = false) {
  const style = level === 1 ? "Heading1" : level === 2 ? "Heading2" : "Heading3";
  return para(text, {
    style,
    bold: true,
    color: level === 1 ? "1F4D78" : "2E74B5",
    size: level === 1 ? 32 : level === 2 ? 26 : 24,
    before: level === 1 ? 300 : 220,
    after: level === 1 ? 180 : 120,
    pageBreakBefore,
    keepNext: true,
  });
}

function bullet(text) {
  return para(text, { numId: 1, after: 80, indent: 720 });
}

function numberItem(text) {
  return para(text, { numId: 2, after: 80, indent: 720 });
}

function note(text) {
  return [
    '<w:tbl><w:tblPr><w:tblW w:w="9360" w:type="dxa"/><w:tblInd w:w="120" w:type="dxa"/>',
    '<w:tblBorders><w:top w:val="single" w:sz="6" w:color="D9E2EC"/><w:left w:val="single" w:sz="6" w:color="D9E2EC"/><w:bottom w:val="single" w:sz="6" w:color="D9E2EC"/><w:right w:val="single" w:sz="6" w:color="D9E2EC"/></w:tblBorders>',
    '<w:tblCellMar><w:top w:w="120" w:type="dxa"/><w:left w:w="180" w:type="dxa"/><w:bottom w:w="120" w:type="dxa"/><w:right w:w="180" w:type="dxa"/></w:tblCellMar></w:tblPr>',
    '<w:tblGrid><w:gridCol w:w="9360"/></w:tblGrid><w:tr><w:tc>',
    '<w:tcPr><w:tcW w:w="9360" w:type="dxa"/><w:shd w:fill="F4F6F9"/></w:tcPr>',
    para(text, { after: 0, bold: true, color: "1F3A5F" }),
    "</w:tc></w:tr></w:tbl>",
    para("", { after: 80 }),
  ].join("");
}

function table(headers, rows, widths = null) {
  const count = headers.length;
  const w = widths || Array(count).fill(Math.floor(9360 / count));
  const fixed = [...w];
  fixed[fixed.length - 1] += 9360 - fixed.reduce((a, b) => a + b, 0);
  const cell = (text, width, header = false) => [
    "<w:tc>",
    `<w:tcPr><w:tcW w:w="${width}" w:type="dxa"/>`,
    header ? '<w:shd w:fill="E8EEF5"/>' : "",
    '<w:vAlign w:val="center"/></w:tcPr>',
    para(text, {
      after: 0,
      bold: header,
      color: header ? "0B2545" : "111827",
      size: header ? 22 : 21,
      line: 280,
    }),
    "</w:tc>",
  ].join("");
  return [
    '<w:tbl><w:tblPr><w:tblW w:w="9360" w:type="dxa"/><w:tblInd w:w="120" w:type="dxa"/>',
    '<w:tblBorders><w:top w:val="single" w:sz="4" w:color="CBD5E1"/><w:left w:val="single" w:sz="4" w:color="CBD5E1"/><w:bottom w:val="single" w:sz="4" w:color="CBD5E1"/><w:right w:val="single" w:sz="4" w:color="CBD5E1"/><w:insideH w:val="single" w:sz="4" w:color="CBD5E1"/><w:insideV w:val="single" w:sz="4" w:color="CBD5E1"/></w:tblBorders>',
    '<w:tblCellMar><w:top w:w="100" w:type="dxa"/><w:left w:w="140" w:type="dxa"/><w:bottom w:w="100" w:type="dxa"/><w:right w:w="140" w:type="dxa"/></w:tblCellMar></w:tblPr>',
    `<w:tblGrid>${fixed.map((x) => `<w:gridCol w:w="${x}"/>`).join("")}</w:tblGrid>`,
    `<w:tr>${headers.map((h, i) => cell(h, fixed[i], true)).join("")}</w:tr>`,
    rows
      .map((row) => `<w:tr>${row.map((c, i) => cell(c, fixed[i], false)).join("")}</w:tr>`)
      .join(""),
    "</w:tbl>",
    para("", { after: 120 }),
  ].join("");
}

function pageBreak() {
  return '<w:p><w:r><w:br w:type="page"/></w:r></w:p>';
}

